// HTTP API, SSE for the UI, WebSocket /api/events for session clients,
// bearer-token auth, Host and Origin checks.

import { timingSafeEqual } from "node:crypto";
import { dirname, join } from "node:path";
import type { Server, ServerWebSocket } from "bun";
import { configMtime, configPath, loadConfig, saveConfig, SESSION_NAME_RE, type Config } from "./config.ts";
import { Hub, type Connection, type StreamMsg, type Transport } from "./hub.ts";
import { AGENT_RE } from "./agent.ts";
import { sha256, type Author } from "./store.ts";
import { OpError, type AnchorInput, type Workspace } from "./workspace.ts";

export interface ServeOptions {
  port: number;
  /** extra listen address besides 127.0.0.1 */
  lan: string | null;
  auth: boolean;
  /** persist workspace additions to the config file */
  persist?: boolean;
  configFile?: string;
  quiet?: boolean;
}

interface WsData {
  session: string;
  cwd?: string;
  transport: Transport;
  agent?: string;
  conn?: Connection;
}

type Ui = { indexHtml: string; appJs: string; appCss: string };

async function loadUi(): Promise<Ui | null> {
  try {
    // generated by scripts/build-ui.ts; absent until the UI is built
    // @ts-ignore
    const m = await import("./ui-assets.ts");
    return m.default as Ui;
  } catch {
    return null;
  }
}

const json = (data: unknown, status = 200, headers: Record<string, string> = {}) =>
  new Response(JSON.stringify(data), { status, headers: { "content-type": "application/json; charset=utf-8", ...headers } });

const err = (status: number, code: string, message: string, extra: Record<string, unknown> = {}) =>
  json({ error: code, message, ...extra }, status);

function safeEqual(a: string, b: string): boolean {
  const x = Buffer.from(a);
  const y = Buffer.from(b);
  return x.length === y.length && timingSafeEqual(x, y);
}

function cookie(req: Request, name: string): string | null {
  const raw = req.headers.get("cookie");
  if (!raw) return null;
  for (const part of raw.split(";")) {
    const [k, ...v] = part.trim().split("=");
    if (k === name) return decodeURIComponent(v.join("="));
  }
  return null;
}

export class PlanchatServer {
  readonly hub: Hub;
  private servers: Server<WsData>[] = [];
  private cfgMtime = 0;
  private ui: Ui | null = null;
  private keepalive: ReturnType<typeof setInterval> | null = null;

  constructor(
    public cfg: Config,
    readonly opts: ServeOptions,
    hub?: Hub,
  ) {
    this.hub = hub ?? new Hub(cfg, { attachmentsPath: join(dirname(opts.configFile ?? configPath()), "attachments.json") });
  }

  get configFile(): string {
    return this.opts.configFile ?? configPath();
  }

  async start(): Promise<void> {
    if (!this.opts.auth && this.opts.lan && !this.opts.quiet) {
      console.error(
        `[planchat] WARNING: listening on ${this.opts.lan} without auth. Anyone on that network can post comments, and comments reach Claude sessions that have shell access.`,
      );
    }
    if (this.opts.auth && Object.keys(this.cfg.tokens).length === 0) {
      throw new Error("auth is on but no tokens exist: run `planchat token add <name> --save`, or start with --no-auth (loopback only)");
    }
    this.cfgMtime = configMtime(this.configFile);
    this.ui = await loadUi();
    this.hub.start();
    const addrs = ["127.0.0.1", ...(this.opts.lan && this.opts.lan !== "127.0.0.1" ? [this.opts.lan] : [])];
    for (const hostname of addrs) {
      this.servers.push(
        Bun.serve<WsData>({
          hostname,
          port: this.opts.port,
          idleTimeout: 0,
          fetch: (req, server) => this.fetch(req, server),
          websocket: {
            open: (ws) => this.wsOpen(ws),
            message: (ws, msg) => this.wsMessage(ws, msg),
            close: (ws) => this.wsClose(ws),
            idleTimeout: 120,
            sendPings: true,
          },
        }),
      );
    }
    this.keepalive = setInterval(() => this.broadcastPing(), 25_000);
    if (!this.opts.quiet) {
      const port = this.servers[0].port;
      console.error(`[planchat] listening on ${addrs.map((a) => `http://${a}:${port}`).join(", ")} (auth ${this.opts.auth ? "on" : "off"})`);
      for (const w of this.hub.workspaces.values()) console.error(`[planchat] workspace ${w.name}: ${w.root}`);
    }
  }

  get port(): number {
    return this.servers[0]?.port ?? this.opts.port;
  }

  stop(): void {
    if (this.keepalive) clearInterval(this.keepalive);
    for (const s of this.servers) s.stop(true);
    this.hub.stop();
  }

  // ---------------------------------------------------------------- auth

  /** Re-read tokens when the config file changes (planchat token add while running). */
  private refreshTokens(): void {
    const m = configMtime(this.configFile);
    if (m && m !== this.cfgMtime) {
      this.cfgMtime = m;
      try {
        this.cfg.tokens = loadConfig(this.configFile).tokens;
      } catch {
        /* keep the old tokens on a half-written file */
      }
    }
  }

  /** Token name for a request, null when unauthenticated. In --no-auth mode every request is the default author. */
  private authName(req: Request, url: URL): string | null {
    if (!this.opts.auth) return this.cfg.defaultAuthor;
    this.refreshTokens();
    let token: string | null = null;
    const h = req.headers.get("authorization");
    if (h?.startsWith("Bearer ")) token = h.slice(7).trim();
    token ??= cookie(req, "planchat_token");
    if (!token && url.pathname === "/") token = url.searchParams.get("token");
    if (!token) return null;
    const hash = sha256(token);
    for (const [name, h2] of Object.entries(this.cfg.tokens)) if (safeEqual(hash, h2)) return name;
    return null;
  }

  private allowedHost(host: string | null): boolean {
    if (!host) return false;
    const port = this.port;
    const ok = new Set([`127.0.0.1:${port}`, `localhost:${port}`, `[::1]:${port}`, ...this.cfg.allowedHosts]);
    if (this.opts.lan) ok.add(`${this.opts.lan.includes(":") ? `[${this.opts.lan}]` : this.opts.lan}:${port}`);
    return ok.has(host.toLowerCase());
  }

  /** Same-origin only for browsers; requests without Origin (CLI) pass. */
  private allowedOrigin(req: Request): boolean {
    const origin = req.headers.get("origin");
    if (origin === null) return true;
    const host = req.headers.get("host");
    return origin === `http://${host}`;
  }

  // ---------------------------------------------------------------- actor

  private actor(req: Request, human: string, mutating: boolean): Author {
    const explicit = req.headers.get("x-planchat-session");
    if (explicit) {
      if (!SESSION_NAME_RE.test(explicit)) throw new OpError(400, "bad_request", `bad session name ${explicit}`);
      return { kind: "session", name: explicit };
    }
    const agent = req.headers.get("x-planchat-agent");
    if (agent) {
      if (!AGENT_RE.test(agent)) throw new OpError(400, "bad_request", `bad agent id ${agent}`);
      const name = this.hub.sessionForAgent(agent);
      if (name) return { kind: "session", name };
      if (mutating && req.headers.get("x-planchat-as-human") !== "1") {
        const how = agent.startsWith("codex:") ? "`planchat attach codex --session <name>`" : "`planchat events --session <name>` under Monitor, or `planchat mcp`";
        throw new OpError(
          400,
          "session_unknown",
          `this request comes from an agent session that is not connected to planchat: pass --session <name>, or connect it first with ${how}; a human in that shell passes --human`,
        );
      }
    }
    return { kind: "human", name: human };
  }

  // --------------------------------------------------------------- fetch

  private async fetch(req: Request, server: Server<WsData>): Promise<Response | undefined> {
    const url = new URL(req.url);
    if (!this.allowedHost(req.headers.get("host"))) return err(403, "bad_host", "unexpected Host header");
    const mutating = req.method !== "GET" && req.method !== "HEAD";
    const upgrade = req.headers.get("upgrade")?.toLowerCase() === "websocket";
    if ((mutating || upgrade) && !this.allowedOrigin(req)) return err(403, "bad_origin", "cross-origin request refused");

    const who = this.authName(req, url);
    if (url.pathname === "/" && who && url.searchParams.has("token")) {
      return new Response(null, {
        status: 302,
        headers: {
          location: "/",
          "set-cookie": `planchat_token=${encodeURIComponent(url.searchParams.get("token")!)}; HttpOnly; SameSite=Strict; Path=/`,
        },
      });
    }
    if (!who) {
      if (url.pathname === "/") {
        return new Response("planchat: token required. Open the URL printed by `planchat token add` (…/?token=…).\n", {
          status: 401,
          headers: { "content-type": "text/plain; charset=utf-8" },
        });
      }
      return err(401, "unauthorized", "missing or unknown token");
    }

    try {
      if (upgrade && url.pathname === "/api/events") return this.upgrade(req, url, server);
      if (!url.pathname.startsWith("/api/")) return this.static(url.pathname);
      return await this.api(req, url, who, mutating);
    } catch (e) {
      if (e instanceof OpError) return err(e.status, e.code, e.message, e.extra);
      if (e instanceof SyntaxError) return err(400, "bad_json", e.message);
      console.error("[planchat] internal error", e);
      return err(500, "internal", e instanceof Error ? e.message : String(e));
    }
  }

  private static(path: string): Response {
    const ui = this.ui;
    const headers = { "cache-control": "no-cache", "x-content-type-options": "nosniff" };
    if (!ui) {
      return new Response("planchat UI is not built; run `bun run build:ui`\n", { status: 503, headers: { ...headers, "content-type": "text/plain" } });
    }
    if (path === "/" || path === "/index.html") {
      return new Response(ui.indexHtml, {
        headers: {
          ...headers,
          "content-type": "text/html; charset=utf-8",
          "content-security-policy": "default-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; frame-ancestors 'none'",
          "x-frame-options": "DENY",
        },
      });
    }
    if (path === "/app.js") return new Response(ui.appJs, { headers: { ...headers, "content-type": "text/javascript; charset=utf-8" } });
    if (path === "/app.css") return new Response(ui.appCss, { headers: { ...headers, "content-type": "text/css; charset=utf-8" } });
    return new Response("not found\n", { status: 404 });
  }

  private upgrade(req: Request, url: URL, server: Server<WsData>): Response | undefined {
    const session = url.searchParams.get("session") ?? "";
    if (!SESSION_NAME_RE.test(session)) return err(400, "bad_request", "session must match " + SESSION_NAME_RE.source);
    const transport = (url.searchParams.get("transport") === "mcp" ? "mcp" : "events") as Transport;
    const data: WsData = {
      session,
      transport,
      cwd: url.searchParams.get("cwd") ?? undefined,
      agent: (() => {
        const a = url.searchParams.get("agent");
        return a && AGENT_RE.test(a) ? a : undefined;
      })(),
    };
    if (server.upgrade(req, { data })) return undefined;
    return err(400, "bad_request", "websocket upgrade failed");
  }

  private async body(req: Request): Promise<Record<string, any>> {
    const text = await req.text();
    if (!text) return {};
    const v = JSON.parse(text);
    if (v === null || typeof v !== "object" || Array.isArray(v)) throw new OpError(400, "bad_request", "JSON object expected");
    return v;
  }

  private async api(req: Request, url: URL, human: string, mutating: boolean): Promise<Response> {
    const p = url.pathname;
    const q = url.searchParams;
    const m = req.method;
    const hub = this.hub;
    const actor = () => this.actor(req, human, mutating);

    if (m === "GET" && p === "/api/me") {
      const a = this.actor(req, human, false);
      return json({
        author: a,
        reactions: this.cfg.reactions,
        workspaces: [...hub.workspaces.values()].map((w) => ({ name: w.name, root: w.root })),
        graceSeconds: this.cfg.graceSeconds,
      });
    }
    if (p === "/api/workspaces") {
      if (m === "GET") return json([...hub.workspaces.values()].map((w) => ({ name: w.name, root: w.root, include: w.cfg.include, exclude: w.cfg.exclude })));
      if (m === "POST") {
        if (actor().kind !== "human") throw new OpError(403, "forbidden", "only a human adds workspaces");
        const b = await this.body(req);
        if (typeof b.name !== "string" || typeof b.root !== "string") throw new OpError(400, "bad_request", "name and root are required");
        const w = hub.addWorkspace({ name: b.name, root: b.root, include: b.include ?? [], exclude: b.exclude ?? [] });
        if (this.opts.persist !== false) {
          const cfg = loadConfig(this.configFile);
          if (!cfg.workspaces.some((x) => x.name === w.name)) cfg.workspaces.push(w.cfg);
          saveConfig(cfg, this.configFile);
          this.cfgMtime = configMtime(this.configFile);
        }
        return json({ name: w.name, root: w.root }, 201);
      }
    }
    if (m === "GET" && p === "/api/sessions") return json(hub.sessions());
    if (m === "GET" && p === "/api/files") {
      const w = hub.ws(q.get("ws"));
      const counts: Record<string, { open: number; total: number }> = {};
      for (const t of w.state.threads.values()) {
        const c = (counts[t.file] ??= { open: 0, total: 0 });
        c.total++;
        if (t.status === "open") c.open++;
      }
      return json({ ws: w.name, files: w.index.list(), threads: counts });
    }
    if (m === "GET" && p === "/api/file") {
      const w = hub.ws(q.get("ws"));
      const path = q.get("path") ?? "";
      const f = w.view(path);
      return json({ ws: w.name, path, content: f.content, hash: f.hash });
    }
    if (m === "GET" && p === "/api/diff") {
      const w = hub.ws(q.get("ws"));
      return json(hub.diff(w, q.get("from") ?? "", q.get("to") ?? ""));
    }
    if (m === "GET" && p === "/api/threads") {
      const wsName = q.get("ws");
      const list = wsName ? [hub.ws(wsName)] : [...hub.workspaces.values()];
      const status = q.get("status") ?? "open";
      const file = q.get("file");
      const since = q.get("since");
      const sinceSeq = since && /^\d+$/.test(since) ? Number(since) : null;
      const sinceTs = since && sinceSeq === null ? since : null;
      const out = list.flatMap((w) =>
        hub.threadViews(
          w,
          [...w.state.threads.values()].filter(
            (t) =>
              (status === "all" || t.status === status) &&
              (!file || t.file === file) &&
              (sinceSeq === null || t.seq > sinceSeq) &&
              (sinceTs === null || t.updated > sinceTs),
          ),
        ),
      );
      return json(out);
    }
    if (m === "POST" && p === "/api/threads") {
      const a = actor();
      const b = await this.body(req);
      const w = b.ws ? hub.ws(b.ws) : b.cwd ? (hub.wsForDir(b.cwd) ?? hub.ws(null)) : hub.ws(null);
      const file = this.relFile(w, b.file);
      const t = w.createThread(a, { file, anchor: b.anchor as AnchorInput, body: b.body });
      return json(hub.threadView(w, t), 201);
    }
    const tm = /^\/api\/threads\/([0-9A-Z]{26})(?:\/(comments|claim|release|resolve|reopen|anchor))?$/.exec(p);
    if (tm) {
      const [, id, action] = tm;
      const w = hub.wsOf(id);
      if (!action && m === "GET") {
        const t = w.thread(id);
        return json(hub.threadView(w, t));
      }
      if (m === "POST") {
        const a = actor();
        const b = await this.body(req);
        switch (action) {
          case "comments":
            return json(hub.threadView(w, w.reply(a, id, b.body)), 201);
          case "claim": {
            const r = w.claim(a, id);
            return json({ ok: r.ok, claimed_by: r.claimed_by, error: r.error, thread: hub.threadView(w, r.thread) }, r.ok ? 200 : 409);
          }
          case "release":
            return json(hub.threadView(w, w.release(a, id)));
          case "resolve":
            return json(hub.threadView(w, w.resolve(a, id)));
          case "reopen":
            return json(hub.threadView(w, w.reopen(a, id)));
          case "anchor":
            return json(hub.threadView(w, w.moveAnchor(a, id, b.anchor as AnchorInput)));
        }
      }
    }
    const cm = /^\/api\/comments\/([0-9A-Z]{26})$/.exec(p);
    if (cm) {
      const w = hub.wsOf(cm[1]);
      if (m === "PATCH") return json(hub.threadView(w, w.editComment(actor(), cm[1], (await this.body(req)).body)));
      if (m === "DELETE") return json(hub.threadView(w, w.deleteComment(actor(), cm[1])));
    }
    if (m === "POST" && p === "/api/reactions") {
      const b = await this.body(req);
      if (typeof b.target !== "string") throw new OpError(400, "bad_request", "target is required");
      const w = hub.wsOf(b.target);
      return json(hub.threadView(w, w.react(actor(), b.target, String(b.kind), b.on !== false)));
    }
    if (m === "POST" && (p === "/api/subscribe" || p === "/api/unsubscribe")) {
      const a = actor();
      if (a.kind !== "session") throw new OpError(400, "bad_request", "subscribe needs a session (--session <name>)");
      const b = await this.body(req);
      const w = b.ws ? hub.ws(b.ws) : b.cwd ? hub.wsForDir(b.cwd) : undefined;
      if (!w) throw new OpError(404, "not_found", "no such workspace (pass ws, or run from inside a workspace root)");
      if (p === "/api/unsubscribe") hub.unsubscribe(a.name, w.name);
      else hub.subscribe(a.name, w.name, Array.isArray(b.globs) ? b.globs.map(String) : []);
      return json(hub.sessions().find((s) => s.name === a.name) ?? { name: a.name, subscriptions: [] });
    }
    if (m === "POST" && (p === "/api/attach" || p === "/api/detach")) {
      const b = await this.body(req);
      const agent = req.headers.get("x-planchat-agent") ?? "";
      const session =
        (typeof b.session === "string" && b.session) || req.headers.get("x-planchat-session") || (agent ? this.hub.sessionForAgent(agent) : undefined) || "";
      if (!session) throw new OpError(400, "bad_request", "session is required");
      if (p === "/api/detach") return json({ session, detached: hub.detach(session) });
      if (b.kind !== "codex") throw new OpError(400, "bad_request", "kind must be codex (Claude Code sessions use planchat events or planchat mcp)");
      const thread = typeof b.thread === "string" && b.thread ? b.thread : agent.startsWith("codex:") ? agent.slice(6) : "";
      if (!thread) throw new OpError(400, "bad_request", "thread is required (run inside Codex, or pass --thread)");
      const r = hub.attachCodex(session, thread, typeof b.cwd === "string" ? b.cwd : undefined);
      return json({ session, thread, ...r });
    }
    if (m === "GET" && p === "/api/stream") return this.stream(q.get("ws"));
    throw new OpError(404, "not_found", `no route for ${m} ${p}`);
  }

  /** Accept a path relative to the workspace root, or an absolute path inside it (CLI convenience). */
  private relFile(w: Workspace, file: unknown): string {
    if (typeof file !== "string" || !file) throw new OpError(400, "bad_request", "file is required");
    if (file.startsWith("/")) {
      if (!file.startsWith(w.root + "/")) throw new OpError(404, "not_found", `${file} is outside workspace ${w.name}`);
      return w.index.relativeOf(file);
    }
    return file;
  }

  // ----------------------------------------------------------------- SSE

  private streams = new Set<ReadableStreamDefaultController<Uint8Array>>();

  private stream(wsFilter: string | null): Response {
    const enc = new TextEncoder();
    let unlisten = () => {};
    let ctl: ReadableStreamDefaultController<Uint8Array>;
    const body = new ReadableStream<Uint8Array>({
      start: (c) => {
        ctl = c;
        this.streams.add(c);
        c.enqueue(enc.encode(`retry: 1000\nevent: hello\ndata: {}\n\n`));
        unlisten = this.hub.listen((msg: StreamMsg) => {
          if (wsFilter && "ws" in msg && msg.ws !== wsFilter) return;
          try {
            c.enqueue(enc.encode(`event: ${msg.type}\ndata: ${JSON.stringify(msg)}\n\n`));
          } catch {
            unlisten();
            this.streams.delete(c);
          }
        });
      },
      cancel: () => {
        unlisten();
        this.streams.delete(ctl);
      },
    });
    return new Response(body, {
      headers: { "content-type": "text/event-stream", "cache-control": "no-cache", connection: "keep-alive", "x-accel-buffering": "no" },
    });
  }

  private broadcastPing(): void {
    const ping = new TextEncoder().encode(`: ping\n\n`);
    for (const c of this.streams) {
      try {
        c.enqueue(ping);
      } catch {
        this.streams.delete(c);
      }
    }
  }

  // ------------------------------------------------------------ websocket

  private wsOpen(ws: ServerWebSocket<WsData>): void {
    const d = ws.data;
    const conn: Connection = {
      session: d.session,
      transport: d.transport,
      agent: d.agent,
      send: (msg) => {
        ws.send(JSON.stringify(msg));
      },
      close: (code, reason) => ws.close(code, reason),
    };
    d.conn = conn;
    const r = this.hub.connect(conn, d.cwd);
    if (!r.ok) {
      d.conn = undefined;
      ws.send(JSON.stringify({ type: "error", error: r.error }));
      ws.close(4009, r.error.slice(0, 120));
    }
  }

  private wsMessage(ws: ServerWebSocket<WsData>, raw: string | Buffer): void {
    const d = ws.data;
    if (!d.conn) return;
    let msg: any;
    try {
      msg = JSON.parse(typeof raw === "string" ? raw : raw.toString("utf8"));
    } catch {
      return;
    }
    if (msg?.type === "ack" && typeof msg.ws === "string" && Number.isInteger(msg.seq)) this.hub.ack(d.session, msg.ws, msg.seq);
    else if (msg?.type === "ping") this.hub.touch(d.session);
  }

  private wsClose(ws: ServerWebSocket<WsData>): void {
    if (ws.data.conn) this.hub.disconnect(ws.data.conn);
  }
}
