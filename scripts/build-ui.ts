// Bundle the UI into dist/ui and generate src/ui-assets.ts, which embeds the
// bundle as text so `bun build --compile` carries it inside the binary.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const out = join(root, "dist", "ui");
mkdirSync(out, { recursive: true });

const result = await Bun.build({
  entrypoints: [join(root, "ui", "main.tsx")],
  target: "browser",
  minify: true,
  sourcemap: "none",
  define: { "process.env.NODE_ENV": '"production"' },
});
if (!result.success) {
  for (const l of result.logs) console.error(l);
  process.exit(1);
}
const js = await result.outputs[0].text();
writeFileSync(join(out, "app.js"), js);
writeFileSync(join(out, "app.css"), readFileSync(join(root, "ui", "style.css"), "utf8"));
writeFileSync(
  join(out, "index.html"),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>planchat</title>
<link rel="stylesheet" href="/app.css">
</head>
<body>
<div id="app"></div>
<script src="/app.js"></script>
</body>
</html>
`,
);
writeFileSync(
  join(root, "src", "ui-assets.ts"),
  `// generated by scripts/build-ui.ts — do not edit
// @ts-ignore
import indexHtml from "../dist/ui/index.html" with { type: "text" };
// @ts-ignore
import appJs from "../dist/ui/app.js" with { type: "text" };
// @ts-ignore
import appCss from "../dist/ui/app.css" with { type: "text" };
export default { indexHtml, appJs, appCss } as unknown as { indexHtml: string; appJs: string; appCss: string };
`,
);
console.log(`ui: ${(js.length / 1024).toFixed(0)} KiB js → ${out}`);
